package com.api.project.ecommerce.model;

/**
 * Enum representing different user roles in the eCommerce application.
 */
public enum AppRole {

    /** Regular user role with basic access privileges. */
    ROLE_USER,

    /** Admin role with higher-level access and management capabilities. */
    ROLE_ADMIN,

    /** Seller role with permissions to list and manage products. */
    ROLE_SELLER
}
